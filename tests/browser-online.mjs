import {createRequire} from 'node:module';
import {spawn} from 'node:child_process';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const server=spawn('.venv/Scripts/python.exe',['-m','tests.serve_online_fixture'],{stdio:'ignore'});
let browser;
try{
 let ready=false;
 for(let i=0;i<40;i++){try{if((await fetch('http://127.0.0.1:8004/api/health')).ok){ready=true;break;}}catch{}await new Promise(r=>setTimeout(r,250));}
 assert.ok(ready,'Servidor de testes online');
 try{browser=await chromium.launch({headless:true});}catch{browser=await chromium.launch({headless:true,channel:'msedge'});}
 const context=await browser.newContext();
 await context.route('https://tile.openstreetmap.org/**',route=>route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256"><rect width="256" height="256" fill="#eee"/></svg>'}));
 await context.route('https://fonts.googleapis.com/**',route=>route.abort());
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8004');
 await page.getByText('Consulte os registros validados.',{exact:false}).waitFor();
 await page.locator('[data-action=new]').first().click();
 await page.locator('[data-action=register]').click();
 await page.locator('#auth-user').fill('colaborador');
 await page.locator('#auth-password').fill('senha-de-teste-cidadao');
 await page.locator('#auth-invite').fill('convite-de-teste');
 await page.locator('[data-action=register-submit]').click();
 await page.locator('.account-name').filter({hasText:'colaborador'}).waitFor();
 assert.equal(await page.locator('nav a[href="#review"]').count(),0);
 await page.locator('[data-action=new]').first().click();
 const data=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=50;c.height=50;return c.toDataURL().split(',')[1];});
 await page.locator('#photo').setInputFiles({name:'teste.png',mimeType:'image/png',buffer:Buffer.from(data,'base64')});
 await page.getByText('Toque para substituir a imagem').waitFor();
 await page.locator('#user-description').fill('Registro controlado para teste.');
 await page.locator('[data-action=local-manual]').click();
 await page.locator('#review-category').selectOption('dano');
 await page.locator('[data-action=submit]').click();
 await page.waitForFunction(()=>!document.querySelector('#modal').open);
 await page.locator('[data-action=detail]').first().click();
 assert.equal(await page.locator('[data-action=validate]').count(),0);
 await page.locator('[data-action=close]').first().click();
 await page.locator('[data-action=logout]').click();
 await page.locator('[data-action=login]').waitFor();
 await page.getByText('Consulte os registros validados.',{exact:false}).waitFor();
 assert.equal(await page.locator('[data-action=detail]').count(),0);
 await page.locator('[data-action=login]').click();
 await page.locator('#auth-user').fill('revisor');
 await page.locator('#auth-password').fill('senha-de-teste-revisor');
 await page.locator('[data-action=login-submit]').click();
 await page.locator('.account-name').filter({hasText:'revisor'}).waitFor();
 await page.locator('nav a[href="#review"]').click();
 await page.locator('[data-action=detail]').first().click();
 await page.locator('[data-action=validate]').click();
 await page.waitForFunction(()=>!document.querySelector('#modal').open);
 await page.locator('[data-action=logout]').click();
 await page.locator('[data-action=login]').waitFor();
 await page.getByText('Consulte os registros validados.',{exact:false}).waitFor();
 assert.equal(await page.locator('[data-action=detail]').count(),1);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 console.log('OK: cadastro por convite, sessão, envio privado, revisão autorizada, consulta pública e celular.');
}finally{await browser?.close();server.kill();}
