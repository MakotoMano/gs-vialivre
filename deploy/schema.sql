CREATE SCHEMA IF NOT EXISTS vialivre;
REVOKE ALL ON SCHEMA vialivre FROM PUBLIC;
CREATE TABLE IF NOT EXISTS vialivre.records (id TEXT PRIMARY KEY, data TEXT NOT NULL, image BYTEA NOT NULL, version INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS vialivre.analyses (id TEXT PRIMARY KEY, image_hash TEXT NOT NULL, result TEXT NOT NULL, created TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS vialivre.users (id TEXT PRIMARY KEY, username TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL, role TEXT NOT NULL CHECK (role IN ('citizen','reviewer')));
CREATE TABLE IF NOT EXISTS vialivre.sessions (token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL, expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS vialivre.quotas (bucket TEXT PRIMARY KEY, hits INTEGER NOT NULL, expires BIGINT NOT NULL);
GRANT USAGE ON SCHEMA vialivre TO vialivre_app;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA vialivre TO vialivre_app;
